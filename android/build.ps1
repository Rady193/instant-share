# Builds Instant Share for Android (android\build\Instant-Share.apk) without Gradle: aapt2 -> javac -> d8 -> zipalign ->
# apksigner, with the same tools as the ScaffERP phone apps.
#
#   powershell -ExecutionPolicy Bypass -File android\build.ps1
#
# (build.py runs this, after writing assets\setup.html with make_setup.py.)
# Needs a JDK 17 and the Android SDK (platforms;android-34, build-tools;34.0.0), by default from
# %LOCALAPPDATA%\ScaffERP-android-tools (jdk\*, sdk\); override with -Jdk / -Sdk. The version comes from
# instantshare.py (VERSION = "1.2.3" -> versionCode 10203, so it always rises).
param(
    [string]$Tools = "$env:LOCALAPPDATA\ScaffERP-android-tools",
    [string]$Jdk = "",
    [string]$Sdk = "",
    [string]$Keystore = ""          # signing key; made on the first build and kept OUTSIDE the repository
)
$ErrorActionPreference = 'Stop'
$here = Split-Path -Parent $MyInvocation.MyCommand.Path
if (-not $Jdk) { $Jdk = (Get-ChildItem "$Tools\jdk" -Directory | Select-Object -First 1).FullName }
if (-not $Sdk) { $Sdk = "$Tools\sdk" }
if (-not $Keystore) { $Keystore = "$Tools\textshare-release.keystore" }
$bt = "$Sdk\build-tools\34.0.0"; $androidJar = "$Sdk\platforms\android-34\android.jar"
foreach ($p in @("$Jdk\bin\javac.exe", "$bt\aapt2.exe", "$bt\d8.bat", "$bt\zipalign.exe", "$bt\apksigner.bat", $androidJar,
                 "$here\assets\setup.html")) {
    if (-not (Test-Path $p)) { throw "Missing $p - see the README (Building from source)." }
}
$env:JAVA_HOME = $Jdk; $env:Path = "$Jdk\bin;$env:Path"

$source = Get-Content "$here\..\instantshare.py" -Raw
if ($source -notmatch '(?m)^VERSION = "(\d+)\.(\d+)\.(\d+)"') { throw "No VERSION in instantshare.py" }
$version = "$($Matches[1]).$($Matches[2]).$($Matches[3])"
$code = [int]$Matches[1] * 10000 + [int]$Matches[2] * 100 + [int]$Matches[3]

function Run($exe, [string[]]$argv) {
    & $exe @argv
    if ($LASTEXITCODE -ne 0) { throw "$([IO.Path]::GetFileName($exe)) failed ($LASTEXITCODE)" }
}

if (-not (Test-Path $Keystore)) {
    Write-Host "== making the signing key $Keystore (keep it: updates must be signed with the same key)"
    Run "$Jdk\bin\keytool.exe" @('-genkeypair', '-keystore', $Keystore, '-alias', 'textshare', '-keyalg', 'RSA', '-keysize', '2048',
        '-validity', '10000', '-storepass', 'textshare', '-keypass', 'textshare', '-dname', 'CN=Instant Share, O=SCAFFApps')
}

$out = "$here\build\work"
Remove-Item $out -Recurse -Force -ErrorAction SilentlyContinue
New-Item -ItemType Directory -Force "$out\gen\com\scaffapps\textshare", "$out\classes", "$out\dex" | Out-Null

Run "$bt\aapt2.exe" @('compile', '--dir', "$here\res", '-o', "$out\res.zip")
Run "$bt\aapt2.exe" @('link', '-o', "$out\base.apk", '-I', $androidJar, '--manifest', "$here\AndroidManifest.xml",
    '--java', "$out\gen", '-A', "$here\assets", '--min-sdk-version', '29', '--target-sdk-version', '34',
    '--version-code', "$code", '--version-name', $version, "$out\res.zip")
Set-Content "$out\gen\com\scaffapps\textshare\BuildInfo.java" -Encoding ascii -Value @"
package com.scaffapps.textshare;
/** Generated by build.ps1 from VERSION in instantshare.py. */
final class BuildInfo { static final String VERSION = "$version"; static final int CODE = $code; private BuildInfo() {} }
"@

# --release 8 takes java.* from the JDK (lambdas need its LambdaMetafactory); android.jar is the Android API
$sources = @(Get-ChildItem "$here\src", "$out\gen" -Recurse -Filter *.java | ForEach-Object { $_.FullName })
Run "$Jdk\bin\javac.exe" (@('-Xlint:-options', '--release', '8', '-encoding', 'UTF-8',
    '-classpath', $androidJar, '-d', "$out\classes") + $sources)
$classes = @(Get-ChildItem "$out\classes" -Recurse -Filter *.class | ForEach-Object { $_.FullName })
Run "$bt\d8.bat" (@('--release', '--lib', $androidJar, '--min-api', '29', '--output', "$out\dex") + $classes)

Copy-Item "$out\base.apk" "$out\unsigned.apk"
Push-Location "$out\dex"; Run "$Jdk\bin\jar.exe" @('uf', "$out\unsigned.apk", 'classes.dex'); Pop-Location
Run "$bt\zipalign.exe" @('-p', '-f', '4', "$out\unsigned.apk", "$out\aligned.apk")
$apk = "$here\build\Instant-Share.apk"
Run "$bt\apksigner.bat" @('sign', '--ks', $Keystore, '--ks-key-alias', 'textshare', '--ks-pass', 'pass:textshare',
    '--key-pass', 'pass:textshare', '--out', $apk, "$out\aligned.apk")
Run "$bt\apksigner.bat" @('verify', $apk)
Write-Host "== Instant Share for Android $version ($code): $apk ($([math]::Round((Get-Item $apk).Length / 1KB)) KB)"
